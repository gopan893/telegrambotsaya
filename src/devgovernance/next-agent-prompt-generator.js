function generatePostCodexReviewPrompt(context) {
  const h = handoff.readHandoff(context?.services);
  const handoffData = h.ok ? h.handoff : {};

  return [
    '# Post-Codex Review Prompt',
    '',
    '## Context',
    'Codex has completed its task. Perform a safety review.',
    '',
    '## Review Checklist',
    '- All tests pass',
    '- No secrets exposed',
    '- Dashboard tabs all render correctly',
    '- No duplicate modules',
    '- Integration contract satisfied',
    '- Handoff updated',
    '- No executor bypass',
    '',
    '## Changes Made',
    ...(Array.isArray(handoffData.filesChanged) ? handoffData.filesChanged.map(f => `- ${f}`) : ['- Unknown']),
    '',
    '---',
    'Generated by DevGovernance Phase 34'
  ].join('\n');
}

function generateNextAgentPrompt(type, context) {
  let prompt;
  switch (type) {
    case 'codex':
      prompt = generateNextCodexPrompt(context);
      break;
    case 'opencode':
      prompt = generateNextOpenCodePrompt(context);
      break;
    case 'recovery':
      prompt = generateRecoveryPrompt(context);
      break;
    case 'p0':
      prompt = generateP0PatchPrompt(context);
      break;
    case 'review':
      prompt = generatePostCodexReviewPrompt(context);
      break;
    default:
      prompt = generateRecoveryPrompt(context);
  }

  const entry = { type, prompt, createdAt: utils.now() };
  store.addNextAgentPrompt(entry, context?.services);
  return { ok: true, type, prompt };
}

module.exports = {
  generateNextCodexPrompt,
  generateNextOpenCodePrompt,
  generateRecoveryPrompt,
  generateP0PatchPrompt,
  generatePostCodexReviewPrompt,
  generateNextAgentPrompt
};
