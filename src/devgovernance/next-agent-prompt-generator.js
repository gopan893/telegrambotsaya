function generateNextOpenCodePrompt(context) {
  const prompt = generateNextCodexPrompt(context);
  return prompt.replace('# Codex Next Task Prompt', '# OpenCode Next Task Prompt')
    .replace('## Tests to Run', '## OpenCode-Specific Notes\n- If P0 issue exists, patch it first\n- Validate dashboard tab registry\n- Check dark form UI\n- Check service worker cache rules\n\n## Tests to Run');
}

function generateRecoveryPrompt(context) {
  const h = handoff.readHandoff(context?.services);
  const handoffData = h.ok ? h.handoff : {};

  const prompt = [
    '# Recovery Agent Prompt',
    '',
    '## Context',
    'Previous agent did not complete its handoff properly. A recovery handoff has been generated.',
    '',
    '## Detected State',
    `Last Agent: ${handoffData.lastAgent || 'Unknown'}`,
    `Current Task: ${handoffData.currentTask || 'Unknown'}`,
    `Files Changed: ${(handoffData.filesChanged || []).length} files`,
    '',
    '## Recovery Steps',
    '1. Read AGENTS.md for contract rules',
    '2. Read AGENT_HANDOFF.md for current state',
    '3. Read ARCHITECTURE_MAP.md for system overview',
    '4. Run `git status` and `git diff` to review uncommitted changes',
    '5. Run `node --check telebot.js`',
    '6. Run related scratch tests',
    '7. Validate integration contract (check dashboard tab registry, routes)',
    '8. Check for duplicate modules or broken routes',
    '9. Continue the task safely from where it was left off',
    '10. Update handoff after completing work',
    '',
    '## What NOT To Do',
    '- Do NOT auto-commit or auto-push',
    '- Do NOT run shell executors',
    '- Do NOT write to GitHub/email/calendar directly',
    '- Do NOT expose secrets or tokens',
    '- Do NOT start new features before auditing the current state',
    '',
    '## Critical Files to Inspect',
    '- AGENTS.md',
    '- AGENT_HANDOFF.md',
    '- docs/ARCHITECTURE_MAP.md',
    '- public/dashboard/state.js (tab registry)',
    '- public/dashboard/ui.js (renderers)',
    '- public/dashboard/index.html (menu)',
    '- src/dashboard/dashboard-routes.js (API routes)',
    '',
    '---',
    'Generated by DevGovernance Phase 34'
  ];
  return prompt.join('\n');
}

